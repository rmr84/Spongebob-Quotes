import { CHARACTER_BY_ID } from '../data/characters';
import raw from '../data/quotes.json';

export interface Quote {
  text: string;
  characterId: string;
  episode: string;
  season: number;
}

export interface QuoteDb {
  quotes: Quote[];
  /** First season each character speaks in (from the full transcripts). */
  debut: Map<string, number>;
  /** Seasons the quotes are drawn from, e.g. [1, 2, 3]. */
  seasons: number[];
}

interface RawDb {
  seasons: number[];
  episodes: { t: string; s: number }[];
  debut: Record<string, number>;
  quotes: [text: string, characterId: string, episodeIndex: number][];
}

function build(data: RawDb): QuoteDb {
  const quotes = data.quotes
    .filter(([, c]) => CHARACTER_BY_ID.has(c))
    .map(([text, characterId, ep]) => ({
      text,
      characterId,
      episode: data.episodes[ep].t,
      season: data.episodes[ep].s,
    }));
  return { quotes, debut: new Map(Object.entries(data.debut)), seasons: data.seasons };
}

/**
 * Generated by `npm run fetch-quotes`. Imported (rather than fetched) so the
 * browser and the API compute the same daily puzzle from the same data.
 */
export const QUOTE_DB: QuoteDb = build(raw as unknown as RawDb);
